function draw(ctx, text, x, y, cell, gap, lw, color) {
  ctx.strokeStyle = color; ctx.lineWidth = lw; ctx.lineCap = "square"; ctx.lineJoin = "miter";
  var cx = x;
  for (var i = 0; i < text.length; i++) {
    var g = G[text[i]]; if (!g) { cx += cell + gap; continue; }
    for (var s = 0; s < g.length; s++) {
      ctx.beginPath();
      for (var p = 0; p < g[s].length; p++) {
        var px = cx + g[s][p][0] * cell, py = y + g[s][p][1] * cell;
        if (p === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py);
      }
      ctx.stroke();
    }
    cx += cell + gap;
  }
}
function width(text, cell, gap) { return text.length * cell + (text.length - 1) * gap; }
